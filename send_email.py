#!/usr/bin/env python3
"""Read a Markdown digest from stdin, render to HTML, send via Gmail SMTP.

Env vars required:
  GMAIL_ADDRESS        — sender Gmail address (also the SMTP login)
  GMAIL_APP_PASSWORD   — 16-char Google App Password
  RECIPIENT_EMAIL      — where the digest is delivered

Usage:
  python send_email.py --subject "AI Demand Watch — 2026-05-22 — 7 new signals" < digest.md
"""
from __future__ import annotations

import argparse
import os
import smtplib
import ssl
import sys
from email.message import EmailMessage

REQUIRED_ENV = ("GMAIL_ADDRESS", "GMAIL_APP_PASSWORD", "RECIPIENT_EMAIL")

HTML_SHELL = """<!DOCTYPE html>
<html><head><meta charset="utf-8"></head>
<body style="font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',system-ui,sans-serif;max-width:680px;margin:0 auto;padding:20px;color:#222;line-height:1.5;">
{body}
<hr style="margin-top:32px;border:none;border-top:1px solid #ddd;">
<p style="color:#888;font-size:12px;">AI Demand Watch · generated by Claude Code on the Web</p>
</body></html>"""


def render_html(md: str) -> str:
    import markdown  # third-party; the trigger session pip-installs it once
    body = markdown.markdown(md, extensions=["extra", "sane_lists", "smarty"])
    return HTML_SHELL.format(body=body)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--subject", required=True, help="Email subject line")
    args = ap.parse_args()

    missing = [k for k in REQUIRED_ENV if not os.environ.get(k)]
    if missing:
        print(f"missing env vars: {', '.join(missing)}", file=sys.stderr)
        return 2

    md = sys.stdin.read()
    if not md.strip():
        print("stdin was empty; refusing to send a blank email", file=sys.stderr)
        return 3

    msg = EmailMessage()
    msg["From"] = os.environ["GMAIL_ADDRESS"]
    msg["To"] = os.environ["RECIPIENT_EMAIL"]
    msg["Subject"] = args.subject
    msg.set_content(md)
    msg.add_alternative(render_html(md), subtype="html")

    ctx = ssl.create_default_context()
    with smtplib.SMTP_SSL("smtp.gmail.com", 465, context=ctx) as s:
        s.login(os.environ["GMAIL_ADDRESS"], os.environ["GMAIL_APP_PASSWORD"])
        s.send_message(msg)

    print(f"sent: {args.subject} -> {os.environ['RECIPIENT_EMAIL']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
